export function message(language: LanguageName, key: MessageKey, values: Record<string, string | number> = {}): string {
  let value = (language === "ru" ? ru : en)[key];
  for (const [name, replacement] of Object.entries(values)) value = value.replaceAll(`{${name}}`, String(replacement));
  return value;
}
